"""Build an additive candidate namespace without modifying legacy documents."""

import argparse
import html
import json
import re
import tempfile
from pathlib import Path

from rdflib import Graph, Literal, OWL, RDF, RDFS, URIRef

from check_catalog import validate_catalog

OLD = "https://scbrown.github.io/quechua/ns"
NEW = "https://w3id.org/intigraph/quechua/ns"
TTL = "ns-stable.ttl"
HTML = "ns-stable.html"


def mapped(node):
    if isinstance(node, URIRef):
        text = str(node)
        if text == OLD or text.startswith(OLD + "#"):
            return URIRef(NEW + text[len(OLD):])
    return node


def expected(source):
    target = Graph()
    for triple in source:
        target.add(tuple(mapped(node) for node in triple))
    # Include the ontology itself and every declared term, including deprecated
    # ones. Neither the old document nor any consumer's stored RDF is rewritten.
    for subject in set(source.subjects()):
        target.add((subject, OWL.sameAs, mapped(subject)))
    return target


def render_html(source):
    terms = sorted(set(source.subjects()) - {URIRef(OLD)}, key=str)
    rows = []
    for term in terms:
        local = str(term)[len(OLD) + 1:]
        kind = "Class" if (term, RDF.type, RDFS.Class) in source else "Property"
        deprecated = " (deprecated)" if (term, OWL.deprecated, Literal(True)) in source else ""
        rows.append(
            f'<tr id="{html.escape(local, quote=True)}"><td>'
            f'<a href="{html.escape(str(mapped(term)), quote=True)}">'
            f'{html.escape(local)}</a></td><td>{kind}{deprecated}</td>'
            f'<td><a href="{html.escape(str(term), quote=True)}">Legacy IRI</a></td></tr>'
        )
    return "\n".join([
        "<!doctype html>", '<html lang="en"><meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        "<title>Quechua stable namespace</title>",
        f'<link rel="alternate" type="text/turtle" href="{TTL}">',
        '<style>body{font:1rem system-ui;max-width:70rem;margin:2rem auto;padding:0 1rem}'
        'td,th{text-align:left;padding:.3rem .8rem}table{border-collapse:collapse}'
        'tr{border-bottom:1px solid #ddd}</style>',
        "<h1>Quechua stable namespace</h1>",
        "<p>The permanent namespace is registered. Existing catalog "
        "documents and stored identifiers are unchanged.</p>",
        f"<p>Namespace: <code>{NEW}#</code>. "
        f'<a href="{TTL}">Turtle declarations and legacy identity links</a>. '
        '<a href="ns.html">Existing catalog</a>.</p>',
        f"<p>{len(terms)} terms, including preserved deprecated declarations.</p>",
        "<table><thead><tr><th>Term</th><th>Kind</th><th>Compatibility</th></tr></thead><tbody>",
        *rows, "</tbody></table></html>", "",
    ])


def write(root, source):
    # Sorted complete RDF terms give deterministic bytes without changing the
    # literal lexical forms, languages or datatypes supplied by the RDF parser.
    lines = []
    for triple in expected(source):
        line = " ".join(node.n3() for node in triple) + " ."
        if triple[:2] == (URIRef(NEW), OWL.versionInfo):
            line += " # x-release-please-version"
        lines.append(line)
    lines.sort()
    (root / TTL).write_text(
        "# Generated by scripts/publish_stable_namespace.py --write\n"
        "# Registered namespace; legacy documents are not modified.\n" + "\n".join(lines) + "\n"
    )
    (root / HTML).write_text(render_html(source))


def validate(root, source):
    actual = Graph().parse(root / TTL, format="turtle")
    wanted = expected(source)
    if set(actual) != set(wanted):
        raise ValueError(
            f"candidate graph differs: {len(set(wanted) - set(actual))} missing, "
            f"{len(set(actual) - set(wanted))} unexpected triples"
        )
    if (root / HTML).read_text() != render_html(source):
        raise ValueError("candidate HTML differs from the declaration catalog")
    return len(set(source.subjects())) - 1, len(actual)


def selftest(source):
    """Prove missing, mispaired, foreign and altered-literal failures."""
    assert mapped(URIRef("https://scbrown.github.io/quechua/ns#Blocker")) == URIRef(
        "https://w3id.org/intigraph/quechua/ns#Blocker"
    )
    assert mapped(URIRef("https://scbrown.github.io/quechua/ns")) == URIRef(
        "https://w3id.org/intigraph/quechua/ns"
    )
    # A text replacement or loose prefix match would corrupt these values.
    for value in (
        URIRef(OLD + "-other#Blocker"),
        URIRef("https://example.org/Blocker"),
        Literal(OLD + "#Blocker", lang="en"),
        Literal("value", datatype=URIRef(OLD + "#Datatype")),
    ):
        assert mapped(value) == value
    print("PASS: exact namespace boundary; literal language/datatype preserved")
    terms = sorted(set(source.subjects()) - {URIRef(OLD)}, key=str)
    assert len(terms) >= 2
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        write(root, source)
        validate(root, source)
        original = (root / TTL).read_bytes()
        for mutation in ("missing", "mispaired", "foreign", "literal", "html"):
            (root / TTL).write_bytes(original)
            (root / HTML).write_text(render_html(source))
            graph = Graph().parse(root / TTL, format="turtle")
            if mutation == "missing":
                graph.remove((mapped(terms[0]), None, None))
            elif mutation == "mispaired":
                graph.remove((terms[0], OWL.sameAs, mapped(terms[0])))
                graph.add((terms[0], OWL.sameAs, mapped(terms[1])))
            elif mutation == "foreign":
                graph.add((URIRef("https://example.org/foreign"), RDF.type, RDFS.Class))
            elif mutation == "literal":
                graph.set((mapped(terms[0]), RDFS.label, Literal("altered")))
            else:
                (root / HTML).write_text("<html>missing terms</html>")
            graph.serialize(root / TTL, format="turtle")
            try:
                validate(root, source)
            except ValueError:
                print(f"PASS refusal: {mutation}")
            else:
                raise AssertionError(f"mutant survived: {mutation}")
        # Model the generic updater's annotated version-line change. The real
        # release bot already bumps the legacy catalog; both representations
        # must describe that same release, without relaxing graph equality.
        write(root, source)
        original = (root / TTL).read_text()
        bumped, count = re.subn(
            r'"[0-9]+\.[0-9]+\.[0-9]+"(?= \. # x-release-please-version)',
            '"99.98.97"', original,
        )
        assert count == 1, "candidate version must have one release annotation"
        released = Graph()
        released += source
        released.set((URIRef(OLD), OWL.versionInfo, Literal("99.98.97")))
        (root / TTL).write_text(bumped)
        validate(root, released)
        (root / TTL).write_text(original)
        try:
            validate(root, released)
        except ValueError:
            print("PASS release bump; stale candidate version refused")
        else:
            raise AssertionError("stale release candidate survived")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    validate_catalog(root)
    config = json.loads((root / "release-please-config.json").read_text())
    extra = config["packages"]["."]["extra-files"]
    if extra.count({"type": "generic", "path": TTL}) != 1:
        raise ValueError("release bot must update the candidate catalog exactly once")
    before = {name: (root / name).read_bytes() for name in ("ns.ttl", "ns.html")}
    source = Graph().parse(root / "ns.ttl", format="turtle")
    if args.write:
        write(root, source)
    terms, triples = validate(root, source)
    if args.selftest:
        selftest(source)
    if any((root / name).read_bytes() != data for name, data in before.items()):
        raise AssertionError("legacy publication changed")
    print(f"PASS: {terms} terms, {triples} candidate triples; legacy files unchanged")


if __name__ == "__main__":
    main()
